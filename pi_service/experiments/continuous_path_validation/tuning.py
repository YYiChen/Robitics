# ========== 视觉与安全 ==========

# 每秒处理多少帧。相机预览延迟高时调小到 15；正常保持 20。
PROCESS_FPS = 20.0

# 连续多少帧没有看到路线后，才允许进入盲区预测。
LINE_LOST_STOP_FRAMES = 3

# 相机暂时看不到胶带时，维持最后一次有效转向的时长（秒）。
# 相机视野不能调整时，可尝试 0.75 到 0.90；不要超过 STOP_SECONDS。
LINE_LOST_PREDICTION_SECONDS = 0.75

# 一直看不到线时的最终安全停车时间（秒）。
# 若车仍会过早停车，可先尝试 1.10；空间狭窄时不要调大。
LINE_LOST_STOP_SECONDS = 1.00

# ========== X 路标计数 ==========

# 同一个 X 连续识别到多少处理帧后才算真正经过。误检时可改为 3。
MARKER_CONFIRM_FRAMES = 2

# X 从画面消失多少处理帧后，才允许下一次计数。预览以 10 FPS 运行时，12 帧约为
# 1.2 秒，可避免同一个 X 在视野边缘闪烁时被重复计数。
MARKER_CLEAR_FRAMES = 12

# 若上一个 X 的候选一直没有消失，但新 X 从画面更上方出现，纵向位置
# 至少下降这个比例就重新解锁计数器。一般无需改；误重复计数再调大。
MARKER_REARM_Y_DROP_RATIO = 0.18

# 本次路线一圈有几个 X 路标。当前贴了四个，所以每累计四次 lap 加 1。
MARKERS_PER_LAP = 4

# ========== 电机功率 ==========

# 正常直线的基础 PWM。当前带发牌机构的车建议从 95 开始；仍走不动再试 105。
STRAIGHT_PWM = 95

# 从静止启动的短时 PWM。车起步困难才增大，通常保持 155。
LAUNCH_PWM = 155

# 转向时看前方目标点的敏感度。普通微调使用这一项；转弯不够可逐步增大。
LOOKAHEAD_GAIN = 200.0

# 远处路线方向对转向的辅助权重。通常保持 0.25。
HEADING_WEIGHT = 0.25

# 小于此值的综合转向误差才视为真正直线。绿底白线的前视偏差较小，
# 不能保持旧值 0.035，否则日志会一直输出左右同速。若蛇形过多再调大。
CORRECTION_DEADBAND = 0.01

# 一旦需要转向，左右轮 PWM 至少相差多少。微调推不动车时可改为 25。
MINIMUM_CORRECTION_PWM = 20

# 转弯时允许的最大左右轮 PWM 差。45 度转弯不够时可改为 145。
MAXIMUM_CORRECTION_PWM = 130

# 转弯时任一侧车轮允许的最低 PWM。0 表示允许内侧轮完全停止。
# 若普通弯道内侧轮转不动，可在网页中提高到 20–60。
MINIMUM_WHEEL_PWM = 0

# 网页和自动循迹都不会输出超过此值的行驶 PWM，避免调参时误设为 255。
MAXIMUM_WHEEL_PWM = 200

# 当前视目标明显偏向一侧时，直接进入强差速转弯，而不是继续用很小的微调。
# 这只依赖路线在画面中的偏差，不假设矩形、八边形或固定左右转。
SHARP_TURN_ERROR = 0.08
SHARP_TURN_CORRECTION_PWM = 55
# 锐弯时采用等幅反向对转，得到原地转向：右转 R=-200/L=+200，
# 左转 R=+200/L=-200。实车符号方向已经按当前电机接线校正。
SHARP_TURN_INNER_PWM = -200
SHARP_TURN_OUTER_PWM = 200

# ========== 视觉起步助推 ==========

# 仅在算法判断为直行时启用。连续观察路线变化这么久；若路线几乎不移动，
# 每次把直行 PWM 增加 MOTION_STEP_PWM，直到路线开始明显移动。
MOTION_OBSERVE_SECONDS = 1.0

# 两次观察之间，主路线骨架的平均位移达到多少像素才算车辆已前进。
# 当前相机视角下路线开始移动时变化很大，可先从 25 开始。
MOTION_MIN_PATH_SHIFT_PX = 25.0

# 车辆未移动时每一轮观察增加的 PWM。通常保持 5。
MOTION_STEP_PWM = 5

# ========== 显示 ==========

# 浏览器实时分析页面端口：http://树莓派IP:5054
DEBUG_WEB_PORT = 5054
